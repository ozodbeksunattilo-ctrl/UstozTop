function toUzbekCyrillic(text) {
  const pairs = [
    [/o['ʻʼ’`]/gi, (match) => match[0] === match[0].toUpperCase() ? 'Ў' : 'ў'],
    [/g['ʻʼ’`]/gi, (match) => match[0] === match[0].toUpperCase() ? 'Ғ' : 'ғ'],
    [/sh/gi, (match) => match[0] === match[0].toUpperCase() ? 'Ш' : 'ш'],
    [/ch/gi, (match) => match[0] === match[0].toUpperCase() ? 'Ч' : 'ч'],
    [/ng/gi, (match) => match[0] === match[0].toUpperCase() ? 'Нг' : 'нг'],
    [/yo/gi, (match) => match[0] === match[0].toUpperCase() ? 'Ё' : 'ё'],
    [/yu/gi, (match) => match[0] === match[0].toUpperCase() ? 'Ю' : 'ю'],
    [/ya/gi, (match) => match[0] === match[0].toUpperCase() ? 'Я' : 'я'],
    [/ye/gi, (match) => match[0] === match[0].toUpperCase() ? 'Е' : 'е'],
  ]
  let result = text
  for (const [pattern, replacement] of pairs) result = result.replace(pattern, replacement)
  result = result.replace(/[ʻʼ’`']/g, '')
  const letters = { a: 'а', b: 'б', d: 'д', e: 'е', f: 'ф', g: 'г', h: 'ҳ', i: 'и', j: 'ж', k: 'к', l: 'л', m: 'м', n: 'н', o: 'о', p: 'п', q: 'қ', r: 'р', s: 'с', t: 'т', u: 'у', v: 'в', x: 'х', y: 'й', z: 'з', "'": '' }
  return result.replace(/[a-zA-Z']/g, (letter) => {
    const converted = letters[letter.toLowerCase()] ?? letter
    return letter === letter.toUpperCase() ? converted.toUpperCase() : converted
  })
}

export function translate(language, text) {
  return translations[language]?.[text] ?? (language === 'uz-Cyrl' ? toUzbekCyrillic(text) : text)
}
